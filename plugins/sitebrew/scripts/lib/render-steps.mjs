// The install guide for a chat window that cannot run commands, written from the same data table the install plan reads (install-items.json).
// Korean first, then English, one section per system. Pure: the same table and compat make the same text. gen-chat-references.mjs writes it to
// skills/setup/references/install-steps.md; a test compares the file with this output.
import { INSTALL_TABLE } from './install-plan.mjs'

const ITEMS = ['node', 'npm', 'git', 'browser', 'kit-clone', 'kit-checkout', 'kit-setup']
const SYSTEMS = [
  { key: 'win32', ko: 'Windows (PowerShell)', en: 'Windows (PowerShell)', slug: 'windows' },
  { key: 'darwin', ko: 'macOS (터미널)', en: 'macOS (Terminal)', slug: 'macos' },
  { key: 'linux', ko: 'Linux (터미널)', en: 'Linux (Terminal)', slug: 'linux' },
]
const HEADER = '<!-- Generated by _tools/gen-chat-references.mjs from scripts/lib/install-items.json. Do not edit by hand. -->'
const LABEL = {
  node: { ko: 'Node.js', en: 'Node.js' },
  npm: { ko: 'npm 올리기', en: 'Update npm' },
  git: { ko: 'Git', en: 'Git' },
  browser: { ko: 'Chrome 또는 Edge', en: 'Chrome or Edge' },
  'kit-clone': { ko: 'Sitebrew 내려받기', en: 'Download Sitebrew' },
  'kit-checkout': { ko: 'Sitebrew 를 고정 태그로 맞추기', en: 'Move Sitebrew to the pinned tag' },
  'kit-setup': { ko: 'Sitebrew 설치', en: 'Install Sitebrew' },
}
const fill = (t, v) => t.replace(/\{(tag|repository|nodeMin|npmMin)\}/g, (_, k) => v[k])
const quoted = (a) => (/\s/.test(a) ? `"${a}"` : a)
// a person gets the plain command: the table's second attempt (no --scope user) when there is one, because an installer that asks for the administrator is normal for a person
const show = (step, v) => fill(step.show ?? (step.fallbackArgv ?? step.argv).map(quoted).join(' '), v)

function section(lang, sys, vars, table) {
  const lines = [`### ${sys[lang]}`, '']
  let kitFirst = 0 // number of the first item that runs inside the Sitebrew folder: it enters with cd, the next one is already there
  ITEMS.forEach((id, n) => {
    const it = table[id]
    const e = it[sys.key] ?? it.all
    lines.push(`**${n + 1}. ${LABEL[id][lang]}**`, '')
    lines.push(fill(it.say[lang], vars), '')
    if (e.steps) {
      const inKit = e.steps.some((s) => s.cwd === 'kit')
      const enter = inKit && !kitFirst // only the first kit item types cd sitebrew; a second cd fails from inside the folder
      if (inKit && !kitFirst) kitFirst = n + 1
      if (enter) lines.push(lang === 'ko' ? 'Sitebrew 를 내려받은 폴더(`sitebrew` 폴더가 들어 있는 폴더)에서 실행해요:' : 'Run it from the folder where you downloaded Sitebrew (the folder that holds the `sitebrew` folder):', '')
      else if (inKit) lines.push(lang === 'ko' ? `\`sitebrew\` 폴더 안에서 실행해요. ${kitFirst}번을 했다면 이미 그 안에 있어요. ${kitFirst}번을 건너뛰었거나 터미널을 새로 열었다면, \`sitebrew\` 가 들어 있는 폴더에서 \`cd sitebrew\` 를 먼저 쳐요:` : `Run it inside the \`sitebrew\` folder. After item ${kitFirst} you are already there. If you skipped item ${kitFirst} or opened a new terminal, first type \`cd sitebrew\` in the folder that holds it:`, '')
      lines.push(sys.key === 'win32' ? '```powershell' : '```bash', ...(enter ? ['cd sitebrew'] : []), ...e.steps.map((s) => show(s, vars)), '```', '')
      if (e.steps.some((s) => s.fallbackArgv)) lines.push(lang === 'ko' ? '윈도우가 관리자 확인 창을 띄우면 「예」를 눌러요.' : 'If Windows shows an administrator prompt, choose Yes.', '')
      for (const s of e.steps) if (s.admin && !s.say?.[lang]) lines.push(lang === 'ko' ? '이 명령은 관리자 암호가 필요할 수 있어요.' : 'This command may ask for the administrator password.', '')
      for (const s of e.steps) if ((s.manualOnly || s.admin) && s.say?.[lang]) lines.push(fill(s.say[lang], vars), '') // the caveat of a command the person must judge (nvm may be missing, apt is Debian only)
    }
    if (e.manual) lines.push(lang === 'ko' ? `이 도구가 없으면: ${fill(e.manual.ko, vars)}` : `If that tool is not available: ${fill(e.manual.en, vars)}`, '')
    const ok = e.success ?? it.success // a system entry may carry its own check (the browser differs per system)
    if (ok) lines.push(lang === 'ko' ? `성공하면: ${fill(ok.ko, vars)}` : `When it works: ${fill(ok.en, vars)}`, '')
    const bad = it.trouble?.[sys.key] ?? it.trouble?.all // what to do when the step stops with an error the person is likely to meet
    if (bad) lines.push(lang === 'ko' ? `문제 해결: ${fill(bad.ko, vars)}` : `Trouble: ${fill(bad.en, vars)}`, '')
  })
  return lines
}

/** @param {{ tag: string, repository: string, nodeMin: string, npmMin: string }} compat the values to write into the text (placeholders are fine: the plugin build fills them) */
export function renderInstallSteps(compat, table = INSTALL_TABLE.items) {
  const vars = { tag: compat.tag, repository: compat.repository, nodeMin: compat.nodeMin, npmMin: compat.npmMin }
  const out = [HEADER, '', '# 설치 안내 (명령을 직접 붙여 넣어요) · Install steps (paste the commands yourself)', '', '## 목차 · Contents', '']
  for (const [lang, name] of [['ko', '한국어'], ['en', 'English']]) {
    out.push(`- ${name}: ${SYSTEMS.map((s) => `[${s[lang]}](#${lang}-${s.slug})`).join(' · ')}`)
  }
  out.push('', '이 안내는 명령을 실행할 수 없는 대화 창에서 써요. 아래 명령을 내 컴퓨터의 터미널에 붙여 넣어요. 계정·키·비용은 필요 없어요. 설치한 뒤에는 터미널을 닫았다 다시 열어요.', '', 'Use this guide in a chat window that cannot run commands. Paste the commands below into the terminal of your own computer. It needs no account, no key and no cost. After installing, close the terminal and open it again.', '')
  for (const [lang, name] of [['ko', '한국어'], ['en', 'English']]) {
    out.push(`## ${name}`, '')
    for (const sys of SYSTEMS) {
      out.push(`<a id="${lang}-${sys.slug}"></a>`, '')
      out.push(...section(lang, sys, vars, table))
    }
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`
}
